-- 1. Tabla para Solicitudes de Reserva
CREATE TABLE IF NOT EXISTS public.reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    hotel_nombre TEXT NOT NULL,
    habitacion TEXT NOT NULL,
    checkin DATE NOT NULL,
    checkout DATE NOT NULL,
    huespedes INTEGER DEFAULT 2,
    nombre_titular TEXT NOT NULL,
    telefono_whatsapp TEXT NOT NULL,
    total_estimado NUMERIC(10, 2),
    estado TEXT DEFAULT 'pendiente' -- pendiente, confirmada, cancelada
);

-- 2. Tabla para Web Check-In Digital
CREATE TABLE IF NOT EXISTS public.web_checkin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    codigo_reserva TEXT NOT NULL,
    documento_titular TEXT NOT NULL,
    hotel_destino TEXT NOT NULL,
    fecha_llegada DATE NOT NULL,
    acompanantes TEXT
);

-- 3. Habilitar Seguridad por Filas (Row Level Security)
ALTER TABLE public.reservas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.web_checkin ENABLE ROW LEVEL SECURITY;

-- 4. Permitir que cualquier visitante de la web pueda registrar una reserva (Insertar)
CREATE POLICY "Permitir inserción pública de reservas" 
ON public.reservas 
FOR INSERT 
TO anon 
WITH CHECK (true);

-- 5. Permitir que cualquier visitante pueda registrar su Web Check-In
CREATE POLICY "Permitir inserción pública de checkin" 
ON public.web_checkin 
FOR INSERT 
TO anon 
WITH CHECK (true);
